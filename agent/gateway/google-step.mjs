// agent/gateway/google-step.mjs: one Gemini step of the turn loop. Turns the gateway's transcript into
// Gemini `contents`, builds the generateContent request, and reads the step back from plain response
// data (candidates[0].content.parts, usageMetadata) rather than SDK getters, so a recorded JSON
// response replays exactly like a live one. The loop itself (tools, guards, fallback) is
// turn-loop.mjs; the Claude side is anthropic-step.mjs.
//
// Two things Gemini 3 and later reject or need, both kept on the function-call parts of history:
//   - thought signatures: the model returns a `thoughtSignature` with a functionCall part and
//     answers HTTP 400 ("Function call is missing a thought_signature in functionCall parts") when a
//     later request replays that call without it. A call this model did not make gets the
//     placeholder Google documents (SKIP_THOUGHT_SIGNATURE);
//   - call ids: gemini-4-argon returns `functionCall.id` (e.g. 'call_334802'); each functionResponse
//     goes back with the same id, and the call keeps it in history.

import { createHash } from 'node:crypto';
import { estimateTokens } from '../context/prompt-blocks.mjs';
import { PROVIDERS } from './model-clients.mjs';

/**
 * The placeholder signature for a function call Gemini did not generate, such as one made by Claude
 * before a fallback moved the turn onto Gemini. Gemini 3 validates the signature on the first
 * function call of every step in the current turn and rejects the request without one; Google
 * documents this value for "functionCall parts that were not generated by the API", as a last resort
 * because it can lower answer quality:
 * https://docs.cloud.google.com/vertex-ai/generative-ai/docs/thought-signatures
 */
export const SKIP_THOUGHT_SIGNATURE = 'skip_thought_signature_validator';

// Gemini's functionDeclarations accept a subset of JSON Schema. An unsupported keyword doesn't fail
// the call, but the model's output is then validated against constraints the API doesn't understand
// and comes back as finishReason=MALFORMED_FUNCTION_CALL: request_probe's minItems/maxItems did that
// deterministically on modest prompts.
const UNSUPPORTED_SCHEMA_KEYS = new Set([
  'minItems', 'maxItems', 'minLength', 'maxLength',
  'pattern', 'default', 'additionalProperties',
  'anyOf', 'oneOf', 'allOf', 'not', '$ref', '$schema',
  'uniqueItems', 'minimum', 'maximum', 'exclusiveMinimum', 'exclusiveMaximum',
  'multipleOf', 'format', 'examples', 'const',
]);

/**
 * A tool's JSON Schema in Gemini's dialect: unsupported keywords removed, types upper-cased.
 *
 * @param {object} schema
 * @returns {object|undefined} a new object; the input is not changed
 */
export function toGoogleSchema(schema) {
  if (!schema) return undefined;
  const copy = JSON.parse(JSON.stringify(schema));
  const convert = (node) => {
    if (!node || typeof node !== 'object') return;
    for (const key of UNSUPPORTED_SCHEMA_KEYS) delete node[key];
    if (typeof node.type === 'string') node.type = node.type.toUpperCase();
    if (node.properties && typeof node.properties === 'object') {
      for (const k of Object.keys(node.properties)) convert(node.properties[k]);
    }
    if (node.items && typeof node.items === 'object') convert(node.items);
  };
  convert(copy);
  return copy;
}

/**
 * The tools as one Gemini tool of function declarations.
 *
 * @param {Record<string, {name: string, description: string, schema: object}>} [tools]
 * @returns {Array|undefined}
 */
export function toGoogleTools(tools) {
  if (!tools) return undefined;
  return [{
    functionDeclarations: Object.values(tools).map((t) => ({
      name: t.name,
      description: t.description,
      parameters: toGoogleSchema(t.schema),
    })),
  }];
}

/**
 * The transcript in Gemini's `contents` shape (see turn-loop.mjs for the transcript format). System
 * messages are skipped: they travel as systemInstruction.
 *
 * A signature is echoed only to the model that produced it. A call another provider made, or another
 * Gemini model (the turn moved to its fallback), gets the documented placeholder instead: a signature
 * is the model's own encoding of its reasoning, and the placeholder is what Google documents for
 * calls the model did not generate.
 *
 * @param {Array<object>} messages
 * @param {object} [o]
 * @param {string} [o.modelId] the Gemini model the contents are for; omitted, every Gemini call counts as its own
 * @returns {Array<{role: 'user'|'model', parts: Array<object>}>}
 */
export function toGoogleContents(messages, { modelId } = {}) {
  const calls = new Map();
  const result = [];
  for (let i = 0; i < messages.length; i++) {
    const msg = messages[i];
    if (msg.role === 'system') continue;

    if (msg.toolCalls && msg.toolCalls.length > 0) {
      result.push({
        role: 'model',
        parts: msg.toolCalls.map((tc) => {
          calls.set(tc.id, tc);
          const functionCall = { name: tc.name, args: tc.args ?? {} };
          if (tc.googleId) functionCall.id = tc.googleId;
          const part = { functionCall };
          // This model's own call: echo its signature, or none if it gave none (an older model).
          // Anything else: the placeholder.
          const ownCall = tc.provider === PROVIDERS.google && (!modelId || !tc.modelId || tc.modelId === modelId);
          const signature = ownCall ? tc.thoughtSignature : SKIP_THOUGHT_SIGNATURE;
          if (signature) part.thoughtSignature = signature;
          return part;
        }),
      });
      continue;
    }

    // N function calls need N function responses in one user turn: batch consecutive tool messages.
    if (msg.role === 'tool') {
      const parts = [];
      let j = i;
      while (j < messages.length && messages[j].role === 'tool') {
        const tm = messages[j];
        const call = calls.get(tm.toolCallId);
        const functionResponse = {
          name: tm.name,
          response: tm.content !== null && typeof tm.content === 'object' ? tm.content : { result: tm.content },
        };
        if (call?.googleId) functionResponse.id = call.googleId;
        parts.push({ functionResponse });
        j++;
      }
      result.push({ role: 'user', parts });
      i = j - 1;
      continue;
    }

    // Content-part arrays join to the same bytes renderBlocks() produces, which is exactly what
    // Gemini's implicit caching keys on.
    const role = msg.role === 'assistant' ? 'model' : 'user';
    const text = Array.isArray(msg.content)
      ? msg.content.map((p) => p?.text || '').join('\n\n')
      : (msg.content || '');
    result.push({ role, parts: [{ text }] });
  }
  return result;
}

/**
 * One Gemini response, read from plain data.
 *
 * @param {object} response the generateContent response (an SDK object or its JSON)
 * @returns {{text: string, calls: Array<{name: string, args: object, googleId?: string, thoughtSignature?: string}>, finishReason: string|undefined, usage: object}}
 */
export function readGoogleStep(response) {
  const candidate = response?.candidates?.[0];
  const parts = candidate?.content?.parts || [];
  const text = parts
    .filter((p) => typeof p.text === 'string' && p.text && !p.thought)
    .map((p) => p.text)
    .join('');
  const calls = parts
    .filter((p) => p.functionCall)
    .map((p) => ({
      name: p.functionCall.name,
      args: p.functionCall.args ?? {},
      ...(p.functionCall.id ? { googleId: p.functionCall.id } : {}),
      ...(p.thoughtSignature ? { thoughtSignature: p.thoughtSignature } : {}),
    }));
  const u = response?.usageMetadata || {};
  return {
    text,
    calls,
    finishReason: candidate?.finishReason,
    usage: {
      input: u.promptTokenCount || 0,
      output: u.candidatesTokenCount || 0,
      cacheRead: u.cachedContentTokenCount || 0,
      cacheWrite: 0,
      reported: Boolean(response?.usageMetadata),
    },
  };
}

// Explicit context caching for the stable system prefix plus tools. The gateway owns the whole
// lifecycle: handles keyed by a hash of model, system text and tools, kept per client, recreated when
// they expire. Nothing is persisted, and any error falls back to sending the prefix inline. Gemini
// caches only prefixes above about 2,048 tokens and enforces the TTL exactly.
const GEMINI_CACHE_FLOOR_TOKENS = 2048;
const explicitCaches = new WeakMap();

async function geminiCachedContent(ai, { modelId, systemText, googleTools, ttlSeconds, now, logger }) {
  let byHash = explicitCaches.get(ai);
  if (!byHash) explicitCaches.set(ai, (byHash = new Map()));
  const toolsJson = googleTools ? JSON.stringify(googleTools) : '';
  const hash = createHash('sha256').update(`${modelId}\n${systemText}\n${toolsJson}`).digest('hex').substring(0, 16);
  const hit = byHash.get(hash);
  if (hit && hit.expiresAtMs > now() + 60_000) return hit.name;
  if (estimateTokens(systemText) < GEMINI_CACHE_FLOOR_TOKENS) return null;
  const cache = await ai.caches.create({
    model: modelId,
    config: {
      systemInstruction: systemText,
      ...(googleTools ? { tools: googleTools } : {}),
      ttl: `${ttlSeconds}s`,
    },
  });
  byHash.set(hash, { name: cache.name, expiresAtMs: now() + ttlSeconds * 1000 });
  logger('INFO', `gemini explicit cache created: ${cache.name} (≈${estimateTokens(systemText)}tok, ttl=${ttlSeconds}s)`);
  return cache.name;
}

/**
 * The Gemini side of one turn: call() runs one step on the transcript, synthesize() runs the single
 * tool-less step a stopped loop gets to answer from what it gathered.
 *
 * @param {object}   o
 * @param {object}   o.client         a GoogleGenAI client (or a fake with models.generateContent)
 * @param {string}   o.modelId
 * @param {string}   o.systemText     the system blocks joined
 * @param {object}   [o.tools]
 * @param {number}   o.maxTokens
 * @param {number}   o.temperature
 * @param {number}   o.topP
 * @param {boolean}  [o.forceToolCall] constrain every step to a function call (the verifier)
 * @param {object}   o.gemini         { explicitCache, explicitCacheTtlSeconds }
 * @param {Function} o.callWithRetry  (fn, label) => fn's result, retried on rate limits
 * @param {Function} o.logger
 * @param {Function} o.now
 */
export function createGoogleStepper({
  client, modelId, systemText, tools, maxTokens, temperature, topP, forceToolCall = false,
  gemini, callWithRetry, logger, now,
}) {
  const googleTools = toGoogleTools(tools);
  // An organ whose every valid answer is a function call (the verifier's report_pass / report_fail)
  // gets mode ANY: it prevents a text-only non-verdict and lowers the malformed-call rate.
  const toolConfig = googleTools && forceToolCall ? { functionCallingConfig: { mode: 'ANY' } } : undefined;
  let cachedContentName = null;
  let cacheResolved = false;

  const inlinePrefix = () => ({
    ...(systemText ? { systemInstruction: systemText } : {}),
    ...(googleTools ? { tools: googleTools } : {}),
  });

  return {
    provider: PROVIDERS.google,

    async call(history, step) {
      if (gemini.explicitCache && !cacheResolved) {
        cacheResolved = true;
        try {
          cachedContentName = await geminiCachedContent(client, {
            modelId, systemText, googleTools, ttlSeconds: gemini.explicitCacheTtlSeconds, now, logger,
          });
        } catch (e) {
          logger('WARN', `gemini explicit cache unavailable (${e.message}); sending the prefix inline`);
          cachedContentName = null;
        }
      }
      const params = {
        model: modelId,
        contents: toGoogleContents(history, { modelId }),
        config: {
          ...(cachedContentName ? { cachedContent: cachedContentName } : inlinePrefix()),
          ...(toolConfig ? { toolConfig } : {}),
          temperature,
          maxOutputTokens: maxTokens,
          topP,
        },
      };
      logger('INFO', `calling Gemini ${modelId} (step ${step})`);
      const response = await callWithRetry(() => client.models.generateContent(params), `Gemini ${modelId} step ${step}`);
      return readGoogleStep(response);
    },

    async synthesize(history) {
      const params = {
        model: modelId,
        contents: toGoogleContents(history, { modelId }),
        config: {
          ...(systemText ? { systemInstruction: systemText } : {}),
          temperature,
          maxOutputTokens: maxTokens,
          topP,
        },
      };
      const response = await callWithRetry(() => client.models.generateContent(params), `Gemini ${modelId} loop synthesis`);
      return readGoogleStep(response);
    },
  };
}
